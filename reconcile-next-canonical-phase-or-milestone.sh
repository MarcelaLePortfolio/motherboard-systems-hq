echo "PRODUCTION_CHANGE=NONE"

echo
echo "=== VERIFY CURRENT REPOSITORY STATE ==="
git status --short

echo
echo "=== SEARCH CANONICAL MILESTONE / PHASE DOCUMENTATION ==="
rg -n -C 10 \
  'MISSION_CONTROL_PROJECT_CONTEXT_ALIGNMENT|AUTHORITATIVE_MISSION_PACKAGE_HANDOFF|PROJECT_SCOPED_MISSION_READ_RUNTIME|phase|corridor|milestone' \
  . \
  -g '*.md' \
  -g '*.txt' \
  -g '*.sh' \
  -g '!node_modules/**' \
  -g '!.git/**' \
  2>/dev/null || true

echo
echo "=== SEARCH SUCCESSOR / DEFERRED SCOPE SIGNALS ==="
