echo "QUESTION_3=DO_ANY_DEFERRED_ITEMS_REMAIN_IN_SCOPE_FOR_THIS_MILESTONE"
echo "QUESTION_4=ARE_ANY_REMAINING_ITEMS_EXPLICITLY_SEPARATE_FUTURE_MILESTONES"
echo "QUESTION_5=DOES_ANY_SUCCESSOR_REQUIRE_NEW_AUTHORITY_OR_RUNTIME_CAPABILITY"
echo "QUESTION_6=IS_ADDITIONAL_IMPLEMENTATION_AUTHORIZATION_REQUIRED"

