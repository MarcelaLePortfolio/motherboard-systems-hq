  'NEXT_PHASE|NEXT_MILESTONE|successor|deferred|remaining scope|future phase|phase closure|milestone closure' \
  . \
  -g '*.md' \
  -g '*.txt' \
  -g '*.sh' \
  -g '!node_modules/**' \
  -g '!.git/**' \
  2>/dev/null || true

