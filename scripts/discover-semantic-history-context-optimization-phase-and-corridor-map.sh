#!/usr/bin/env bash
set -euo pipefail

echo "=== DISCOVER SEMANTIC HISTORY CONTEXT OPTIMIZATION PHASE AND CORRIDOR MAP ==="

echo
echo "=== BASELINE ==="
echo "BRANCH=$(git branch --show-current)"
echo "HEAD=$(git rev-parse --short=8 HEAD)"
echo "COMMIT=$(git log -1 --format=%s)"
git status --short

echo
echo "=== VERIFY SCOPE-CLASSIFICATION CHECKPOINT ==="

expected_head="5ff4d05f"

if [[ "$(git rev-parse --short=8 HEAD)" != "$expected_head" ]]; then
  echo "STOP: HEAD no longer matches semantic-history scope-classification checkpoint $expected_head."
  exit 2
fi

unexpected="$(
  git status --porcelain |
  grep -vE '^\?\? scripts/discover-semantic-history-context-optimization-phase-and-corridor-map\.sh$|^ M scripts/discover-semantic-history-context-optimization-phase-and-corridor-map\.sh$' ||
  true
)"

if [[ -n "$unexpected" ]]; then
  echo "STOP: unexpected working-tree changes exist:"
  printf '%s\n' "$unexpected"
  exit 2
fi

echo "SCOPE_CLASSIFICATION_CHECKPOINT=CONFIRMED"

echo
echo "=== VERIFY GOVERNING SCOPE ==="

grep -nE \
  'OPTIMIZATION_SCOPE=|SEMANTIC_HISTORY_RANKING_STATUS=|TOKEN_BUDGET_STATUS=|HYBRID_CONTEXT_STATUS=|MODEL_RUNTIME_CONTEXT_STATUS=|BOUNDED_HISTORY_WINDOW_STATUS=|SCOPE_ORDERING_PRINCIPLE=|IMPLEMENTATION_AUTHORIZED=|NEXT_ACTION=|DISCOVER_SEMANTIC_HISTORY_CONTEXT_OPTIMIZATION_PHASE_AND_CORRIDOR_MAP' \
  scripts/classify-semantic-history-context-optimization-scope.sh

echo "GOVERNING_SCOPE=CONFIRMED"

echo
echo "=== VERIFY ARCHITECTURAL INVESTIGATION FOUNDATION ==="

for file in \
  docs/architecture/SEMANTIC_HISTORY_INVENTORY.md \
  docs/architecture/SEMANTIC_HISTORY_SELECTION_OBJECTIVES.md \
  docs/architecture/SEMANTIC_HISTORY_BEHAVIORAL_VALIDATION.md \
  docs/architecture/SEMANTIC_HISTORY_REPOSITORY_READINESS.md
do
  [[ -f "$file" ]] || {
    echo "STOP: required architecture document missing: $file"
    exit 2
  }
  echo "FOUND=$file"
done

echo "ARCHITECTURAL_INVESTIGATION_FOUNDATION=CONFIRMED"

echo
echo "=== DISCOVER PHASE AND CORRIDOR MAP ==="

cat <<'MAP'
