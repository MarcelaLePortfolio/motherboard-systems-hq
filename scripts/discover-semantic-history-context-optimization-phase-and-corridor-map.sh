  OPTIMIZATION_INTEGRATION_AND_CLOSURE

ORDERING_RATIONALE=
  SEMANTIC_SELECTION_REQUIREMENTS_MUST_BE_CLASSIFIED_BEFORE_BUDGETING_OR_WINDOW_POLICY
  BUDGET_AND_WINDOW_REQUIREMENTS_MUST_BE_CLASSIFIED_BEFORE_HYBRID_CONTEXT_COORDINATION
  HYBRID_AND_MODEL_CONTEXT_BOUNDARIES_MUST_BE_CLASSIFIED_BEFORE_INTEGRATED_OPTIMIZATION_VALIDATION
  IMPLEMENTATION_MUST_NOT_PRECEDE_REQUIREMENT_OWNERSHIP_AND_BOUNDARY_CLASSIFICATION

