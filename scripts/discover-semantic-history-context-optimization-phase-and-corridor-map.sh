  CLASSIFY_SEMANTIC_RANKING_REQUIREMENT
MAP

echo
echo "=== VERIFY DISCOVERY-ONLY CHANGE SURFACE ==="

changed="$(
  git diff --name-only |
  grep -vE '^scripts/discover-semantic-history-context-optimization-phase-and-corridor-map\.sh$' ||
  true
)"

if [[ -n "$changed" ]]; then
  echo "STOP: files outside phase-and-corridor discovery scope changed:"
  printf '%s\n' "$changed"
  exit 2
fi

echo "DISCOVERY_ONLY_CHANGE_SURFACE_CONFIRMED"

echo
echo "=== DIFF CHECK ==="
git diff --check
