#!/usr/bin/env bash
set -euo pipefail

echo "=== CLASSIFY PROMPT PRESENTATION COMPLEXITY AND PARENT-CHILD IDENTITY RISK ==="

test "$(git branch --show-current)" = "feature/support-source-references-runtime"
test -z "$(git status --porcelain)"
git merge-base --is-ancestor e032ec20 HEAD

corridor="scripts/investigate-prompt-and-response-contract-presentation.sh"
ollama="scripts/utils/ollamaChat.ts"

for artifact in "$corridor" "$ollama"; do
  test -f "$artifact"
  echo "PRESENT=$artifact"
done

echo
echo "=== VERIFY CURRENT CORRIDOR STATE ==="
grep -q 'CORRIDOR_1_STATUS=' "$corridor"
grep -q '^ACTIVE$' <(awk '/CORRIDOR_1_STATUS=/{getline; print}' "$corridor")
grep -q 'NEXT_ACTION=' "$corridor"
grep -q '^CLASSIFY_PROMPT_PRESENTATION_COMPLEXITY_AND_PARENT_CHILD_IDENTITY_RISK$' \
  <(awk '/NEXT_ACTION=/{getline; print}' "$corridor")
echo "CORRIDOR_STATE=CONFIRMED"

echo
echo "=== VERIFY DUAL IDENTITY PRESENTATION ==="
grep -q 'Bounded project context evidence:' "$ollama"
grep -q 'Source: ${item.relativePath}:${item.lineNumber}' "$ollama"
grep -q 'Project-context segment candidates:' "$ollama"
grep -q 'relativePath = ${item.relativePath}' "$ollama"
grep -q 'sourceStartLine = ${item.sourceStartLine}' "$ollama"
grep -q 'sourceEndLine = ${item.sourceEndLine}' "$ollama"
echo "DUAL_IDENTITY_PRESENTATION=CONFIRMED"

echo
echo "=== VERIFY MODEL MUST MAP CHILD SELECTION TO PARENT SUPPORT ==="
grep -q 'selectedContextSegments records semantic project-context admission; supportSourceReferences records support provenance' "$ollama"
grep -q 'For project-context support, use type project_context_excerpt with the exact relativePath and lineNumber supplied' "$ollama"
grep -q 'Never use a Segment source line range, sourceStartLine, sourceEndLine, or child segment line number as a project_context_excerpt support identity' "$ollama"
grep -q 'project-context support without selecting a supplied child segment for that parent' "$ollama"
echo "PARENT_CHILD_MAPPING_REQUIREMENT=CONFIRMED"

cat <<'MAP'
