PROMPT_AND_RESPONSE_CONTRACT_PRESENTATION

INVESTIGATION_UNIT=
PROMPT_PRESENTATION_COMPLEXITY_AND_PARENT_CHILD_IDENTITY_RISK

CURRENT_PRESENTATION_MODEL=
PARENT_PROJECT_CONTEXT_SOURCE_IDENTITIES
PLUS
CHILD_SEGMENT_SELECTION_IDENTITIES

PARENT_IDENTITY=
RELATIVE_PATH_COLON_PARENT_LINE_NUMBER

CHILD_IDENTITY=
RELATIVE_PATH_PLUS_SOURCE_START_LINE_PLUS_SOURCE_END_LINE

MODEL_REQUIRED_CROSS_MAPPING=
SELECT_CHILD_SEGMENTS_FOR_SEMANTIC_ADMISSION
WHILE
CITING_ONLY_PARENT_SOURCE_IDENTITIES_FOR_SUPPORT_PROVENANCE

