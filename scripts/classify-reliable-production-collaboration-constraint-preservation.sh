#!/usr/bin/env bash
set -euo pipefail

echo "=== CLASSIFY RELIABLE PRODUCTION COLLABORATION CONSTRAINT PRESERVATION ==="

test "$(git branch --show-current)" = "feature/support-source-references-runtime"
test -z "$(git status --porcelain)"
git merge-base --is-ancestor f8f8f530 HEAD

