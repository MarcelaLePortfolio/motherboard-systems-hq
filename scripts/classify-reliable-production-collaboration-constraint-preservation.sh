  test -f "$artifact"
  echo "PRESENT=$artifact"
done

echo
echo "=== VERIFY CORRIDOR 3 CLOSURE ==="
grep -q 'CORRIDOR_3_STATUS=' "$ownership"
grep -q '^COMPLETE$' <(awk '/CORRIDOR_3_STATUS=/{getline; print}' "$ownership")
grep -q 'NEXT_CORRIDOR=' "$ownership"
grep -q '^CONSTRAINT_PRESERVATION$' <(awk '/NEXT_CORRIDOR=/{getline; print}' "$ownership")
echo "CORRIDOR_3_CLOSURE=CONFIRMED"

echo
echo "=== VERIFY STARTING INVARIANTS ==="
grep -q 'FAIL_CLOSED_VALIDATION=' "$starting_boundary"
grep -q 'MUST_BE_PRESERVED' "$starting_boundary"
grep -q 'MATILDA_SEMANTIC_AUTHORSHIP=' "$starting_boundary"
grep -q 'ONE_OLLAMA_INVOCATION=' "$starting_boundary"
echo "STARTING_INVARIANTS=CONFIRMED"

cat <<'MAP'
