  'FAILURE_CLASS=|STRUCTURED_SEMANTIC_SUPPORT_IDENTITY_REJECTION|DETERMINISTIC_VALIDATOR=|PRESERVE|FAIL_CLOSED_BEHAVIOR=|PRESERVE' \
  scripts/classify-preserved-unseeded-acceptance-boundary-failure.sh \
  scripts/classify-source-excerpt-fixed-seed-single-run-failure.sh \
  scripts/classify-phase-3-fail-closed-contract-preservation.sh \
  2>/dev/null || true

echo "FAILURE_CHARACTERIZATION_EVIDENCE=CONFIRMED"

echo
echo "=== VERIFY DIAGNOSTIC CONTROL EVIDENCE ==="

grep -nE \
  'FIXED_SEED=424242|10_OF_10_FIXTURE_SEMANTIC_PASS|0_OF_10_FAIL_CLOSED_OR_RUNTIME_REJECTION|EXACT_REPEATABILITY_OBSERVED=YES|DIAGNOSTIC_CANDIDATE_RESULT=SUPPORTED' \
  scripts/classify-bounded-fixed-seed-diagnostic-result.sh

