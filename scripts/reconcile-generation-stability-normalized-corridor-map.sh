  '1_OF_10_FIXTURE_SEMANTIC_PASS|9_OF_10_FAIL_CLOSED_OR_RUNTIME_REJECTION|2_UNIQUE_EXACT_OUTPUT_FINGERPRINTS' \
  scripts/classify-bounded-fixed-seed-diagnostic-result.sh

