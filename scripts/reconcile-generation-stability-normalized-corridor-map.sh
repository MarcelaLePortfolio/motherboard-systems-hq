  'CURRENT_PRODUCTION_GENERATION_PATH=|CURRENT_PRODUCTION_GENERATION_POLICY=|VALIDATION_ONLY_CONTROL=|CORRIDOR_1_RESULT=RECONCILED' \
  scripts/classify-current-production-generation-behavior.sh

