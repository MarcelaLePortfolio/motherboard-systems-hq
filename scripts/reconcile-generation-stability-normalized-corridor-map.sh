  'TOTAL_RUNS=10|FIXTURE_SEMANTIC_PASS_RUNS=0|FAIL_CLOSED_OR_RUNTIME_REJECTION_RUNS=8|FIXTURE_SEMANTIC_FAILURE_RUNS=2|UNIQUE_EXACT_OUTPUT_FINGERPRINTS=3|PHASE_3_PRODUCTION_STABILITY_RESULT=|UNSTABLE' \
  scripts/classify-phase-3-repeated-unseeded-validation-result.sh

