echo
echo "=== VERIFY CURRENT CHECKPOINT ==="
expected_head="f5e136f5"

if [[ "$(git rev-parse --short=8 HEAD)" != "$expected_head" ]]; then
  echo "STOP: HEAD no longer matches expected reconciliation starting checkpoint $expected_head."
  exit 2
fi

unexpected="$(
  git status --porcelain |
  grep -vE '^\?\? scripts/reconcile-generation-stability-normalized-corridor-map\.sh$|^ M scripts/reconcile-generation-stability-normalized-corridor-map\.sh$' ||
  true
)"

if [[ -n "$unexpected" ]]; then
  echo "STOP: unexpected working-tree changes exist:"
  printf '%s\n' "$unexpected"
  exit 2
fi

echo "CURRENT_CHECKPOINT=CONFIRMED"

echo
echo "=== VERIFY GENERATION STABILITY CLOSURE ANCESTOR ==="

