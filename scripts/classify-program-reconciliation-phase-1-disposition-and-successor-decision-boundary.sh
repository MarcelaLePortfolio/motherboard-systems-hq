DO_NOT_INVENT_OR_PROMOTE_A_RUNTIME_SUCCESSOR_WITHOUT_NEW_EVIDENCE

PERMITTED_NEXT_DECISION_CLASSES=
CLOSE_PROGRAM_RECONCILIATION_WITH_NO_RUNTIME_SUCCESSOR_ESTABLISHED
OR
ESTABLISH_A_NEW_INVESTIGATION_MILESTONE_ONLY_IF_CURRENT_REPOSITORY_EVIDENCE_SUPPORTS_A_DISTINCT_UNRESOLVED_PROGRAM_QUESTION

