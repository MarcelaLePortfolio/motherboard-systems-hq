#!/usr/bin/env bash
set -euo pipefail

echo "=== CLASSIFY RELIABLE PRODUCTION COLLABORATION INTERVENTION BOUNDARY ==="

test "$(git branch --show-current)" = "feature/support-source-references-runtime"
test -z "$(git status --porcelain)"
git merge-base --is-ancestor 254f202b HEAD

constraints="scripts/classify-reliable-production-collaboration-constraint-preservation.sh"
ownership="scripts/investigate-production-collaboration-failure-ownership.sh"
baseline="scripts/reconcile-current-production-failure-baseline.sh"
causal="scripts/classify-failure-repeatability-and-causal-boundary.sh"

for artifact in "$constraints" "$ownership" "$baseline" "$causal"; do
  test -f "$artifact"
  echo "PRESENT=$artifact"
done

echo
echo "=== VERIFY CORRIDOR 4 CLOSURE ==="
grep -q 'CORRIDOR_4_STATUS=' "$constraints"
grep -q '^COMPLETE$' <(awk '/CORRIDOR_4_STATUS=/{getline; print}' "$constraints")
grep -q 'NEXT_CORRIDOR=' "$constraints"
grep -q '^INTERVENTION_BOUNDARY$' <(awk '/NEXT_CORRIDOR=/{getline; print}' "$constraints")
echo "CORRIDOR_4_CLOSURE=CONFIRMED"

echo
echo "=== VERIFY FAILURE OWNERSHIP ==="
grep -q 'PRIMARY_FAILURE_OWNER_CLASS=' "$ownership"
grep -q '^MODEL_GENERATION_LAYER$' <(awk '/PRIMARY_FAILURE_OWNER_CLASS=/{getline; print}' "$ownership")
grep -q 'PRECISE_MODEL_INTERNAL_ROOT_CAUSE=' "$ownership"
grep -q '^NOT_ESTABLISHED$' <(awk '/PRECISE_MODEL_INTERNAL_ROOT_CAUSE=/{getline; print}' "$ownership")
echo "FAILURE_OWNERSHIP=CONFIRMED"

echo
echo "=== VERIFY GENERATION CONTROL SENSITIVITY WITHOUT REMEDY ==="
grep -q 'GENERATION_LAYER_SENSITIVITY_ESTABLISHED' "$causal"
grep -q 'FIXED_SEED_AS_ROOT_CAUSE=' "$causal"
grep -q 'FIXED_SEED_AS_PRODUCTION_REMEDY=' "$causal"
grep -q 'NOT_ESTABLISHED' "$causal"
echo "GENERATION_CONTROL_SENSITIVITY=CONFIRMED"

cat <<'MAP'
PROGRAM=
MATILDA_CONVERSATION_ENGINE

