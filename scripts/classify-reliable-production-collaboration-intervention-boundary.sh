MODEL_CAPABILITY
OTHER_BOUNDED_GENERATION_INPUT_CONDITIONS

ORDER_RATIONALE=
INVESTIGATE_THE_LOWEST_SCOPE_GENERATION_LAYER_SURFACES_FIRST_WHILE_PRESERVING_EXISTING_ARCHITECTURAL_AND_SEMANTIC_GUARDS

