#!/usr/bin/env bash
set -euo pipefail

cd "$(git rev-parse --show-toplevel)"

RESULT="docs/checkpoints/MATILDA_UI_503_REPLACEMENT_CONTROLLED_COMPARISON_RESULT.txt"

printf '%s\n' \
  'CHECKPOINT=MATILDA_UI_SMOKE_TEST_503' \
  'MODE=CLASSIFY_REPLACEMENT_CONTROLLED_COMPARISON' \
  'ISSUE_RESOLVED=NO' \
  'NEW_OLLAMA_INVOCATION=NO' \
  'PRODUCTION_CHANGE=NO'

CONTROLLED_COUNT="$(grep -c '^=== CONTROLLED RUN [0-9][0-9]*/10 ===$' "$RESULT" || true)"
ACCEPTED_COUNT="$(grep -c '"accepted": true' "$RESULT" || true)"
REJECTED_COUNT="$(grep -c '"accepted": false' "$RESULT" || true)"

printf '\n=== COMPLETION EVIDENCE ===\n'
echo "CONTROLLED_RUN_BLOCKS=$CONTROLLED_COUNT"
echo "CONTROLLED_ACCEPTED=$ACCEPTED_COUNT"
echo "CONTROLLED_REJECTED=$REJECTED_COUNT"

printf '\n=== FAILURE CLASSES ===\n'
grep '"failureClass":' "$RESULT" | sort | uniq -c || true

printf '\n=== FINAL MARKERS ===\n'
grep -E \
  '^=== COMPARISON SUMMARY ===$|^=== ACCEPTANCE BOUNDARY ===$|^PRIMARY_CONTROL_CRITERION|^COMPARATIVE_CRITERION|^SEMANTIC_CRITERION|^ISSUE_RESOLVED=' \
  "$RESULT" || true

printf '\n=== CLASSIFICATION ===\n'
if [[ "$CONTROLLED_COUNT" -eq 10 ]] \
  && grep -q '^=== COMPARISON SUMMARY ===$' "$RESULT" \
  && grep -q '^=== ACCEPTANCE BOUNDARY ===$' "$RESULT"; then
  printf '%s\n' \
    'REPLACEMENT_CONTROLLED_COMPARISON_COMPLETE=YES' \
    'CONTROLLED_RUNS_CAPTURED=10_OF_10' \
    "CONTROLLED_ACCEPTED=${ACCEPTED_COUNT}" \
    "CONTROLLED_REJECTED=${REJECTED_COUNT}"
else
  printf '%s\n' \
    'REPLACEMENT_CONTROLLED_COMPARISON_COMPLETE=NO' \
    "CONTROLLED_RUNS_CAPTURED=${CONTROLLED_COUNT}_OF_10" \
    'NEXT_ACTION=DO_NOT_START_ANOTHER_EXPERIMENT;CLASSIFY_INCOMPLETE_RUN'
  exit 1
fi

if [[ "$ACCEPTED_COUNT" -eq 10 ]]; then
  printf '%s\n' \
    'PRIMARY_CONTROL_CRITERION=PASS' \
    'NEXT_ACTION=REVIEW_SEMANTIC_PRESERVATION_BEFORE_ANY_PRODUCTION_DECISION'
else
  printf '%s\n' \
    'PRIMARY_CONTROL_CRITERION=FAIL' \
    'NEXT_ACTION=CLASSIFY_CONTROLLED_FAILURE_PATTERN_BEFORE_ANY_PRODUCTION_DECISION'
fi

printf '\n=== SAFETY BOUNDARY ===\n'
printf '%s\n' \
  'PRODUCTION_SEED_AUTHORIZED=NO' \
  'PRODUCTION_POLICY_CHANGE_AUTHORIZED=NO' \
  'VALIDATOR_CHANGE_AUTHORIZED=NO' \
  'VALIDATOR_WEAKENING_AUTHORIZED=NO' \
  'MODEL_CHANGE_AUTHORIZED=NO' \
  'RETRY_CHANGE_AUTHORIZED=NO' \
  'ISSUE_RESOLVED=NO'

git status --short
