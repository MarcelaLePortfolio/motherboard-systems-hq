#!/usr/bin/env bash
set -euo pipefail

echo "=== CLASSIFY PRODUCTION BEHAVIORAL RELIABILITY CONFIRMATION SUFFICIENCY ==="

test "$(git branch --show-current)" = "feature/support-source-references-runtime"
git merge-base --is-ancestor e30ee03c HEAD
test -z "$(git status --porcelain)"

corridor2="scripts/close-reliability-contract-reconciliation-and-enter-production-behavioral-reliability-confirmation.sh"
test -f "$corridor2"

grep -q 'CORRIDOR_2_STATUS=' "$corridor2"
grep -q '^ACTIVE$' \
  <(awk '/CORRIDOR_2_STATUS=/{getline; print}' "$corridor2")

grep -q 'EXISTING_POST_PROMOTION_BEHAVIORAL_EVIDENCE=' "$corridor2"
grep -q '^10_OF_10_SEMANTIC_PASS$' \
  <(awk '/EXISTING_POST_PROMOTION_BEHAVIORAL_EVIDENCE=/{getline; print}' "$corridor2")

grep -q 'EXISTING_UNSUPPORTED_PROVENANCE_FAILURES=' "$corridor2"
grep -q '^0_OF_10$' \
  <(awk '/EXISTING_UNSUPPORTED_PROVENANCE_FAILURES=/{getline; print}' "$corridor2")

grep -q 'EXISTING_FAIL_CLOSED_OR_RUNTIME_REJECTIONS=' "$corridor2"
grep -q '^0_OF_10$' \
  <(awk '/EXISTING_FAIL_CLOSED_OR_RUNTIME_REJECTIONS=/{getline; print}' "$corridor2")

cat <<'MAP'
PROGRAM=
